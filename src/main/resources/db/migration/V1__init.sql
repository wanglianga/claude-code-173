-- =====================================================================
-- V1__init.sql : 无人货柜补货/盘点/临期下架 核心 schema
-- =====================================================================

-- ---------- 基础资料 ----------
CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(64)  NOT NULL,
    role          VARCHAR(24)  NOT NULL CHECK (role IN ('ADMIN','OPERATOR','STAFF','FINANCE','SUPPLIER','CUSTOMER')),
    supplier_id   BIGINT,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP  NOT NULL DEFAULT now()
);

CREATE TABLE supplier (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code      VARCHAR(32) NOT NULL UNIQUE,
    name      VARCHAR(128) NOT NULL,
    contact   VARCHAR(128),
    bear_loss BOOLEAN NOT NULL DEFAULT TRUE,   -- 临期/温控报损是否由供应商承担
    created_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE product (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku              VARCHAR(64) NOT NULL UNIQUE,
    name             VARCHAR(128) NOT NULL,
    category         VARCHAR(64)  NOT NULL,
    supplier_id      BIGINT NOT NULL REFERENCES supplier(id),
    unit_price       NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    cost_price       NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (cost_price >= 0),
    shelf_life_days  INT NOT NULL CHECK (shelf_life_days > 0),
    temp_requirement VARCHAR(16) NOT NULL DEFAULT 'AMBIENT'
        CHECK (temp_requirement IN ('AMBIENT','CHILLED','FROZEN')),
    active           BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE machine (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(32) NOT NULL UNIQUE,
    name          VARCHAR(128) NOT NULL,
    location_type  VARCHAR(16) NOT NULL CHECK (location_type IN ('COMMUNITY','OFFICE','HOSPITAL')),
    address       VARCHAR(256),
    machine_type  VARCHAR(16) NOT NULL CHECK (machine_type IN ('AMBIENT','CHILLED','FROZEN')),
    temp_min      NUMERIC(5,2),
    temp_max      NUMERIC(5,2),
    locked        BOOLEAN NOT NULL DEFAULT FALSE,   -- 温控异常时锁定补货/销售
    status        VARCHAR(16) NOT NULL DEFAULT 'ONLINE' CHECK (status IN ('ONLINE','OFFLINE')),
    created_at    TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE slot (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id BIGINT NOT NULL REFERENCES machine(id),
    code       VARCHAR(16) NOT NULL,                 -- 货道编号 A01...
    product_id BIGINT REFERENCES product(id),        -- 当前应陈列商品（运营品类调整时变更）
    capacity   INT NOT NULL DEFAULT 10,
    UNIQUE (machine_id, code)
);

-- ---------- 批次（补货/售卖/下架/报损/结算 均追踪到批次） ----------
CREATE TABLE batch (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no        VARCHAR(48) NOT NULL UNIQUE,
    product_id      BIGINT NOT NULL REFERENCES product(id),
    supplier_id     BIGINT NOT NULL REFERENCES supplier(id),
    production_date DATE NOT NULL,
    expiry_date     DATE NOT NULL,
    inbound_qty     INT NOT NULL CHECK (inbound_qty > 0),
    created_at      TIMESTAMP NOT NULL DEFAULT now(),
    CHECK (expiry_date >= production_date)
);

-- ---------- 补货 ----------
CREATE TABLE replenishment (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    replenish_no VARCHAR(48) NOT NULL UNIQUE,
    machine_id   BIGINT NOT NULL REFERENCES machine(id),
    staff_id     BIGINT NOT NULL REFERENCES app_user(id),
    status       VARCHAR(16) NOT NULL DEFAULT 'PLANNED'
        CHECK (status IN ('PLANNED','IN_PROGRESS','COMPLETED')),
    photo_url    VARCHAR(512),
    note         VARCHAR(512),
    created_at   TIMESTAMP NOT NULL DEFAULT now(),
    completed_at TIMESTAMP
);

CREATE TABLE replenishment_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    replenishment_id BIGINT NOT NULL REFERENCES replenishment(id),
    batch_id         BIGINT NOT NULL REFERENCES batch(id),
    slot_id          BIGINT NOT NULL REFERENCES slot(id),    -- 应放货道（系统/补货员申报）
    actual_slot_id   BIGINT REFERENCES slot(id),             -- 实际落入货道（视觉/RFID 复核）
    qty              INT NOT NULL CHECK (qty > 0),
    temp_requirement VARCHAR(16) NOT NULL,
    state            VARCHAR(16) NOT NULL DEFAULT 'PLACED'
        CHECK (state IN ('PLACED','MISPLACED','JAMMED','REMOVED')),
    created_at       TIMESTAMP NOT NULL DEFAULT now()
);

-- ---------- 开门会话 与 可回放事件 ----------
CREATE TABLE door_session (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_no     VARCHAR(48) NOT NULL UNIQUE,
    machine_id     BIGINT NOT NULL REFERENCES machine(id),
    user_id        BIGINT NOT NULL REFERENCES app_user(id),
    opened_at      TIMESTAMP NOT NULL DEFAULT now(),
    closed_at      TIMESTAMP,
    video_clip_url VARCHAR(512),
    status         VARCHAR(16) NOT NULL DEFAULT 'OPEN'
        CHECK (status IN ('OPEN','CLOSED','DISPUTED')),
    note           VARCHAR(256)
);

CREATE TABLE event_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  BIGINT REFERENCES door_session(id),
    machine_id  BIGINT NOT NULL REFERENCES machine(id),
    seq         INT NOT NULL,
    event_type  VARCHAR(24) NOT NULL
        CHECK (event_type IN ('DOOR_OPEN','DOOR_CLOSE','PICK','PUT_BACK',
                              'RECOGNITION','WEIGHT','RFID','TEMPERATURE','JAM')),
    method      VARCHAR(16) CHECK (method IS NULL OR method IN ('VISION','WEIGHT','RFID','SENSOR','MANUAL')),
    payload     VARCHAR(4000) NOT NULL DEFAULT '{}',
    confidence  NUMERIC(4,3),
    occurred_at TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (session_id, seq)
);
CREATE INDEX idx_event_log_session ON event_log(session_id, seq);

CREATE TABLE recognition_result (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES door_session(id),
    event_id   BIGINT NOT NULL REFERENCES event_log(id),
    method     VARCHAR(16) NOT NULL CHECK (method IN ('VISION','WEIGHT','RFID')),
    product_id BIGINT REFERENCES product(id),
    batch_id   BIGINT REFERENCES batch(id),
    confidence NUMERIC(4,3) NOT NULL,
    verdict    VARCHAR(16) NOT NULL CHECK (verdict IN ('CORRECT','UNCERTAIN','REJECTED')),
    detail     VARCHAR(4000) NOT NULL DEFAULT '{}',
    created_at TIMESTAMP NOT NULL DEFAULT now()
);

-- ---------- 订单 ----------
CREATE TABLE order_info (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no    VARCHAR(48) NOT NULL UNIQUE,
    session_id  BIGINT NOT NULL UNIQUE REFERENCES door_session(id),
    machine_id  BIGINT NOT NULL REFERENCES machine(id),
    user_id     BIGINT NOT NULL REFERENCES app_user(id),
    status      VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING','CONFIRMED','CANCELLED','DISPUTED','REFUNDED','PARTIALLY_REFUNDED')),
    total_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    evidence    VARCHAR(20) NOT NULL DEFAULT 'SUFFICIENT'
        CHECK (evidence IN ('SUFFICIENT','INSUFFICIENT')),
    created_at  TIMESTAMP NOT NULL DEFAULT now(),
    settled_at  TIMESTAMP
);
CREATE INDEX idx_order_user ON order_info(user_id);

CREATE TABLE order_item (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT NOT NULL REFERENCES order_info(id),
    product_id  BIGINT NOT NULL REFERENCES product(id),
    batch_id    BIGINT REFERENCES batch(id),
    qty         INT NOT NULL CHECK (qty > 0),
    unit_price  NUMERIC(12,2) NOT NULL,
    amount      NUMERIC(12,2) NOT NULL,
    source      VARCHAR(16) NOT NULL DEFAULT 'RECOGNITION'
        CHECK (source IN ('RECOGNITION','MANUAL_REVIEW')),
    refunded_qty INT NOT NULL DEFAULT 0
);

-- ---------- 库存（当前 + 流水） ----------
CREATE TABLE inventory (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id BIGINT NOT NULL REFERENCES machine(id),
    slot_id    BIGINT NOT NULL REFERENCES slot(id),
    batch_id   BIGINT NOT NULL REFERENCES batch(id),
    qty        INT NOT NULL DEFAULT 0,
    version    BIGINT NOT NULL DEFAULT 0,
    UNIQUE (slot_id, batch_id)
);

CREATE TABLE inventory_ledger (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id  BIGINT NOT NULL REFERENCES machine(id),
    slot_id     BIGINT NOT NULL REFERENCES slot(id),
    batch_id    BIGINT NOT NULL REFERENCES batch(id),
    change_qty  INT NOT NULL,             -- 正=入，负=出
    balance_qty INT NOT NULL,
    reason      VARCHAR(24) NOT NULL
        CHECK (reason IN ('RESTOCK','SALE','PUT_BACK','OFF_SHELF','LOSS',
                          'STOCKTAKE_ADJUST','MISPLACE_IN','MISPLACE_OUT')),
    ref_type    VARCHAR(24),
    ref_id      BIGINT,
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX idx_ledger_batch ON inventory_ledger(batch_id, created_at);
CREATE INDEX idx_ledger_machine ON inventory_ledger(machine_id, created_at);

-- ---------- 温控 ----------
CREATE TABLE temperature_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id  BIGINT NOT NULL REFERENCES machine(id),
    temp_c      NUMERIC(5,2) NOT NULL,
    status      VARCHAR(10) NOT NULL CHECK (status IN ('NORMAL','WARNING','CRITICAL')),
    occurred_at TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX idx_templog_machine ON temperature_log(machine_id, occurred_at);

CREATE TABLE temperature_alert (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_no    VARCHAR(48) NOT NULL UNIQUE,
    machine_id  BIGINT NOT NULL REFERENCES machine(id),
    started_at  TIMESTAMP NOT NULL,
    ended_at    TIMESTAMP,
    min_temp    NUMERIC(5,2),
    max_temp    NUMERIC(5,2),
    status      VARCHAR(12) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','RESOLVED')),
    resolution  VARCHAR(24) CHECK (resolution IS NULL OR resolution IN ('RESTORED','CONDEMNED','RELEASED')),
    note        VARCHAR(256)
);

CREATE TABLE quality_hold (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id  BIGINT NOT NULL REFERENCES machine(id),
    batch_id    BIGINT NOT NULL REFERENCES batch(id),
    reason      VARCHAR(20) NOT NULL CHECK (reason IN ('TEMP_ABUSE','SUSPECT_BATCH','COMPLAINT')),
    status      VARCHAR(12) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','RELEASED','CONDEMNED')),
    created_at  TIMESTAMP NOT NULL DEFAULT now(),
    resolved_at TIMESTAMP,
    note        VARCHAR(256)
);

-- ---------- 临期/下架 ----------
CREATE TABLE off_shelf_task (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_no      VARCHAR(48) NOT NULL UNIQUE,
    machine_id   BIGINT NOT NULL REFERENCES machine(id),
    slot_id      BIGINT NOT NULL REFERENCES slot(id),
    batch_id     BIGINT NOT NULL REFERENCES batch(id),
    qty          INT NOT NULL CHECK (qty > 0),
    reason       VARCHAR(20) NOT NULL
        CHECK (reason IN ('NEAR_EXPIRY','EXPIRED','TEMP_ABUSE','MISPLACED','DAMAGED')),
    status       VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING','DONE','SKIPPED','CONVERTED_LOSS')),
    operator_id  BIGINT REFERENCES app_user(id),
    note         VARCHAR(256),
    created_at   TIMESTAMP NOT NULL DEFAULT now(),
    completed_at TIMESTAMP
);

CREATE TABLE loss_record (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loss_no     VARCHAR(48) NOT NULL UNIQUE,
    batch_id    BIGINT NOT NULL REFERENCES batch(id),
    machine_id  BIGINT REFERENCES machine(id),
    slot_id     BIGINT REFERENCES slot(id),
    qty         INT NOT NULL CHECK (qty > 0),
    reason      VARCHAR(20) NOT NULL
        CHECK (reason IN ('EXPIRED','TEMP_ABUSE','DAMAGED','STOCKTAKE_DIFF','MISPLACED')),
    ref_type    VARCHAR(24),
    ref_id      BIGINT,
    cost_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    bearer      VARCHAR(12) NOT NULL DEFAULT 'SUPPLIER' CHECK (bearer IN ('SUPPLIER','OPERATOR')),
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX idx_loss_batch ON loss_record(batch_id);

-- ---------- 盘点 ----------
CREATE TABLE stocktake (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stocktake_no VARCHAR(48) NOT NULL UNIQUE,
    machine_id   BIGINT NOT NULL REFERENCES machine(id),
    operator_id  BIGINT NOT NULL REFERENCES app_user(id),
    status       VARCHAR(12) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED')),
    note         VARCHAR(256),
    created_at   TIMESTAMP NOT NULL DEFAULT now(),
    closed_at    TIMESTAMP
);

CREATE TABLE stocktake_item (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stocktake_id BIGINT NOT NULL REFERENCES stocktake(id),
    slot_id      BIGINT NOT NULL REFERENCES slot(id),
    batch_id     BIGINT REFERENCES batch(id),
    system_qty   INT NOT NULL,
    actual_qty   INT,
    diff_qty     INT,
    state        VARCHAR(12) NOT NULL DEFAULT 'PENDING'
        CHECK (state IN ('PENDING','MATCH','MISMATCH','RESOLVED')),
    resolution   VARCHAR(20)
        CHECK (resolution IS NULL OR resolution IN ('LOSS','FOUND_MISPLACED','SYSTEM_CORRECTED'))
);

-- ---------- 投诉 / 退款 ----------
CREATE TABLE complaint (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_no  VARCHAR(48) NOT NULL UNIQUE,
    user_id       BIGINT NOT NULL REFERENCES app_user(id),
    order_id      BIGINT NOT NULL REFERENCES order_info(id),
    type          VARCHAR(20) NOT NULL CHECK (type IN ('WRONG_CHARGE','QUALITY','NOT_TAKEN','OTHER')),
    description   VARCHAR(512),
    status        VARCHAR(24) NOT NULL DEFAULT 'OPEN'
        CHECK (status IN ('OPEN','INVESTIGATING','REFUNDED','REJECTED','MANUAL_REVIEW')),
    handler_id    BIGINT REFERENCES app_user(id),
    resolution    VARCHAR(512),
    created_at    TIMESTAMP NOT NULL DEFAULT now(),
    resolved_at   TIMESTAMP
);

CREATE TABLE refund (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_no    VARCHAR(48) NOT NULL UNIQUE,
    complaint_id BIGINT NOT NULL REFERENCES complaint(id),
    order_id     BIGINT NOT NULL REFERENCES order_info(id),
    amount       NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    reason       VARCHAR(256),
    created_at   TIMESTAMP NOT NULL DEFAULT now()
);

-- ---------- 供应商结算 ----------
CREATE TABLE settlement (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_no  VARCHAR(48) NOT NULL UNIQUE,
    supplier_id    BIGINT NOT NULL REFERENCES supplier(id),
    period_start   DATE NOT NULL,
    period_end     DATE NOT NULL,
    sales_amount   NUMERIC(12,2) NOT NULL DEFAULT 0,
    loss_amount    NUMERIC(12,2) NOT NULL DEFAULT 0,
    payable_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    status         VARCHAR(12) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT','CONFIRMED','PAID')),
    created_at     TIMESTAMP NOT NULL DEFAULT now(),
    confirmed_at   TIMESTAMP,
    CHECK (period_end >= period_start)
);

CREATE TABLE settlement_item (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_id BIGINT NOT NULL REFERENCES settlement(id),
    batch_id      BIGINT NOT NULL REFERENCES batch(id),
    sold_qty      INT NOT NULL DEFAULT 0,
    sales_amount  NUMERIC(12,2) NOT NULL DEFAULT 0,
    loss_qty      INT NOT NULL DEFAULT 0,
    loss_amount   NUMERIC(12,2) NOT NULL DEFAULT 0,
    payable_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    UNIQUE (settlement_id, batch_id)
);

-- ---------- 品类（点位陈列）调整 ----------
CREATE TABLE assortment_adjustment (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id     BIGINT NOT NULL REFERENCES machine(id),
    slot_id        BIGINT NOT NULL REFERENCES slot(id),
    old_product_id BIGINT REFERENCES product(id),
    new_product_id BIGINT REFERENCES product(id),
    reason         VARCHAR(256),
    operator_id    BIGINT NOT NULL REFERENCES app_user(id),
    created_at     TIMESTAMP NOT NULL DEFAULT now()
);

-- ---------- 领域事件归档（outbox / Kafka 回放） ----------
CREATE TABLE domain_event_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic        VARCHAR(64) NOT NULL,
    event_key    VARCHAR(128),
    event_type   VARCHAR(64) NOT NULL,
    payload      TEXT NOT NULL,
    occurred_at  TIMESTAMP NOT NULL DEFAULT now(),
    published_at TIMESTAMP
);
CREATE INDEX idx_domain_event_unpublished ON domain_event_log(published_at, id);
